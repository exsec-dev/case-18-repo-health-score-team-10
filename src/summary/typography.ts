// Правило языка продукта для текстов модели: длинное тире → среднее, «ё» → «е»,
// числовой промежуток – через дефис («40-69»).
// Модуль без зависимостей: его берут и конвейер (до валидатора), и веб-бандл (тексты,
// записанные до введения правила, нормализуются при выводе). Числа, маркеры и слова не меняются.
export function normalizeTypography(text: string): string {
  return text.replaceAll("—", "–").replace(/(\d)–(?=\d)/g, "$1-").replaceAll("ё", "е").replaceAll("Ё", "Е");
}
