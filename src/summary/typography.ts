// typography.ts — правило языка продукта для текстов модели (В5.2, Б7; решение
// Екатерины 25.09): длинное тире → среднее, «ё» → «е». Чистый модуль без зависимостей:
// его берут и конвейер (до валидатора), и веб-бандл (при выводе — тексты, записанные
// до правила, аудит дизайна О7). Только орфография: числа, маркеры и слова не меняются.
export function normalizeTypography(text: string): string {
  return text.replaceAll("—", "–").replaceAll("ё", "е").replaceAll("Ё", "Е");
}
